<?php

declare(strict_types=1);

namespace MauticPlugin\KopexaOpsBundle\Service;

use Mautic\CoreBundle\Security\Permissions\CorePermissions;
use Mautic\UserBundle\Entity\Role;
use Mautic\UserBundle\Model\RoleModel;

/**
 * Brings Mautic roles to the state declared in the Helm values
 * (mautic.roles, passed as MAUTIC_ROLES JSON):
 *
 * - roles are matched by name; an existing role (created in the UI or by an
 *   earlier run) is adopted and keeps its ID, so its users stay assigned;
 * - description, admin flag and permissions are set to the declared values;
 *   permissions are replaced completely (Mautic purges the old ones on save);
 * - nothing is written when a role already matches ("unchanged");
 * - roles that are not declared are never touched, and removing a role from
 *   the values does not delete it;
 * - unknown keys, bundles or permissions are errors: all roles are validated
 *   before anything is written.
 *
 * Permissions are generated by Mautic's RoleModel (bitmasks in the
 * permissions table, readable_permissions for the UI), never written as SQL.
 */
class RoleSync
{
    private const ROLE_KEYS = ['name', 'description', 'isAdmin', 'permissions'];

    public function __construct(
        private readonly RoleModel $roles,
        private readonly CorePermissions $security,
    ) {
    }

    /**
     * @return list<array{name: string, description: string, isAdmin: bool, permissions: array<string, list<string>>}>
     *
     * @throws \InvalidArgumentException on any invalid role
     */
    public function parse(string $json): array
    {
        try {
            $data = json_decode($json, true, 64, JSON_THROW_ON_ERROR);
        } catch (\JsonException $e) {
            throw new \InvalidArgumentException('MAUTIC_ROLES is not valid JSON: '.$e->getMessage());
        }
        if (!is_array($data) || !array_is_list($data)) {
            throw new \InvalidArgumentException('MAUTIC_ROLES must be a JSON list of roles.');
        }

        // Mautic builds its permission objects lazily.
        $this->security->getPermissionObjects();

        $errors = [];
        $roles  = [];
        $names  = [];
        foreach ($data as $i => $role) {
            $where = sprintf('role %d', $i + 1);
            if (!is_array($role)) {
                $errors[] = "$where: must be an object";
                continue;
            }
            $name  = is_string($role['name'] ?? null) ? trim($role['name']) : '';
            $where = '' !== $name ? sprintf('role "%s"', $name) : $where;
            foreach (array_diff(array_keys($role), self::ROLE_KEYS) as $key) {
                $errors[] = "$where: unknown key \"$key\" (allowed: ".implode(', ', self::ROLE_KEYS).')';
            }
            if ('' === $name || mb_strlen($name) > 191) {
                $errors[] = "$where: \"name\" is required (at most 191 characters)";
                continue;
            }
            if (isset($names[mb_strtolower($name)])) {
                $errors[] = "$where: declared twice";
                continue;
            }
            $names[mb_strtolower($name)] = true;
            if (isset($role['description']) && !is_string($role['description'])) {
                $errors[] = "$where: \"description\" must be a string";
            }
            if (isset($role['isAdmin']) && !is_bool($role['isAdmin'])) {
                $errors[] = "$where: \"isAdmin\" must be true or false";
            }
            $isAdmin     = true === ($role['isAdmin'] ?? false);
            $permissions = [];
            $raw         = $role['permissions'] ?? [];
            if (!is_array($raw) || ([] !== $raw && array_is_list($raw))) {
                $errors[] = "$where: \"permissions\" must be a map like {\"lead:leads\": [\"full\"]}";
                $raw = [];
            }
            foreach ($raw as $bundleLevel => $perms) {
                if (!is_string($bundleLevel) || 1 !== preg_match('/^[a-z0-9_]+:[a-z0-9_]+$/i', $bundleLevel)) {
                    $errors[] = "$where: \"$bundleLevel\" is not of the form bundle:level (e.g. lead:leads)";
                    continue;
                }
                if (!is_array($perms) || [] === $perms || !array_is_list($perms)) {
                    $errors[] = "$where: \"$bundleLevel\" needs a non-empty list of permissions, e.g. [\"full\"]";
                    continue;
                }
                [$bundle] = explode(':', $bundleLevel);
                if (false === $this->security->getPermissionObject($bundle, false)) {
                    $errors[] = "$where: unknown bundle \"$bundle\" in \"$bundleLevel\"";
                    continue;
                }
                foreach ($perms as $perm) {
                    if (!is_string($perm) || !$this->security->checkPermissionExists($bundleLevel.':'.$perm)) {
                        $errors[] = sprintf('%s: unknown permission "%s:%s"', $where, $bundleLevel, is_scalar($perm) ? (string) $perm : gettype($perm));
                        continue;
                    }
                    $permissions[$bundleLevel][] = $perm;
                }
            }
            if ($isAdmin && [] !== $permissions) {
                $errors[] = "$where: administrators have all permissions; remove \"permissions\" or set \"isAdmin\": false";
            }
            $roles[] = [
                'name'        => $name,
                'description' => (string) ($role['description'] ?? ''),
                'isAdmin'     => $isAdmin,
                'permissions' => self::normalize($permissions),
            ];
        }

        if ([] !== $errors) {
            throw new \InvalidArgumentException("invalid roles:\n  - ".implode("\n  - ", $errors));
        }

        return $roles;
    }

    /**
     * @param array{name: string, description: string, isAdmin: bool, permissions: array<string, list<string>>} $declared
     *
     * @return array{status: 'created'|'updated'|'unchanged', id: int, changed: list<string>}
     */
    public function apply(array $declared, bool $dryRun = false): array
    {
        $role  = $this->roles->getRepository()->findOneBy(['name' => $declared['name']]);
        $isNew = !$role instanceof Role;
        $role ??= new Role();

        $changed = [];
        if ($isNew || (string) $role->getDescription() !== $declared['description']) {
            $changed[] = 'description';
        }
        if ($isNew || (bool) $role->getIsAdmin() !== $declared['isAdmin']) {
            $changed[] = 'isAdmin';
        }
        $current = $role->isAdmin() ? [] : self::normalize((array) ($role->getRawPermissions() ?? []));
        if ($isNew || $current !== $declared['permissions']) {
            $changed[] = 'permissions';
        }
        if (!$isNew && [] === $changed) {
            return ['status' => 'unchanged', 'id' => (int) $role->getId(), 'changed' => []];
        }
        if ($dryRun) {
            return ['status' => $isNew ? 'created' : 'updated', 'id' => (int) $role->getId(), 'changed' => $changed];
        }

        $role->setName($declared['name']);
        $role->setDescription($declared['description']);
        $role->setIsAdmin($declared['isAdmin']);
        // Same path as Mautic's role form: Mautic computes the bitmasks and
        // stores the readable permissions; saveEntity() purges the old ones.
        $this->roles->setRolePermissions($role, $declared['isAdmin'] ? [] : $declared['permissions']);
        $this->roles->saveEntity($role);

        return ['status' => $isNew ? 'created' : 'updated', 'id' => (int) $role->getId(), 'changed' => $changed];
    }

    /**
     * @param array<mixed> $permissions
     *
     * @return array<string, list<string>>
     */
    private static function normalize(array $permissions): array
    {
        $out = [];
        foreach ($permissions as $bundleLevel => $perms) {
            $list = array_values(array_unique(array_map('strval', (array) $perms)));
            sort($list);
            if ([] !== $list) {
                $out[(string) $bundleLevel] = $list;
            }
        }
        ksort($out);

        return $out;
    }
}
